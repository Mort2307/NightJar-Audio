import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const api=readFileSync('functions/src/index.ts','utf8');
const app=readFileSync('src/App.tsx','utf8');
const client=readFileSync('src/platform/firebase-media.ts','utf8');
const admin=readFileSync('src/components/AdminInstallBranding.tsx','utf8');
const workflow=readFileSync('.github/workflows/firebase-hosting-merge.yml','utf8');
const start=api.indexOf('type BrandLogoRemoval=');
const end=api.indexOf('export const retryBrandLogoCleanup = onCall',start);
assert.ok(start>0&&end>start,'Logo removal and durable retry helpers exist');
const block=api.slice(start,end);
const cleanup=block.slice(block.indexOf('const cleanupRetiredBrandLogos='),block.indexOf('export const getBranding = onCall'));
const remove=block.slice(block.indexOf('export const removeBrandLogo = onCall'));
assert.match(cleanup,/brandLogoReceipts/);
assert.match(cleanup,/safeBrandLogoPath\(receipt\)/,'Never delete arbitrary Storage paths');
assert.match(cleanup,/\[current\.logoAssetId,current\.pendingLogoAssetId\]\.includes\(receipt\.id\)/,'Never delete a still-attached logo');
assert.match(cleanup,/getStorage\(\)\.bucket\(\)\.file\(receipt\.path\)\.delete/);
assert.match(cleanup,/storageRemovalPendingPath:null/,'Only confirmed Storage removal clears image receipt');
assert.match(remove,/requireAdminIdentity\(request\)/);
assert.match(remove,/db\.runTransaction\(async tx=>/);
assert.match(remove,/const assets=ids\.map/);
assert.match(remove,/asset\.kind!=='brand_logo'/);
assert.match(remove,/safeBrandLogoPath\(entry\)/);
assert.match(remove,/safeBrandIconPath\(path\)/);
assert.match(remove,/tx\.set\(ref,\{/);
assert.match(remove,/brandLogoRemovalPending:retired,brandIconRemovalPending:retiredIcons/);
assert.match(remove,/tx\.set\(assets\[i\]/);
assert.ok(remove.indexOf('cleanupRetiredBrandLogos()')>remove.indexOf('tx.set(ref,{'),'Storage cleanup must occur after canonical retirement');
assert.doesNotMatch(remove,/await clearBrandingIconFiles\(data\)/,'Old icons must not delete before Firestore detach');
assert.doesNotMatch(remove,/await clearAssetFile\(asset\.data\(\)/,'No blind delete-before-detach');
assert.match(block,/logoCleanupPending: brandLogoReceipts\(data\)\.length > 0/,'Public branding exposes only cleanup state');
assert.match(api,/export const retryBrandLogoCleanup = onCall/);
const upload=api.slice(api.indexOf('export const submitImageAsset = onCall'),api.indexOf('export const getPendingImagePreview ='));
assert.match(upload,/const brandingRef=db\.collection\('settings'\)\.doc\('branding'\)/);
assert.match(upload,/brandLogoRemovalPending:pending/);
assert.match(upload,/Prior pending brand logo cleanup needs retry/);
assert.match(upload,/const retiredIcons=\[\.\.\.new Set\(/,'Approval retains displaced icon receipts');
assert.match(upload,/brandLogoRemovalPending:retiredLogos/,'Approval receipts displaced logo');
assert.match(api,/retirement\.kind==='brand_logo'\?await cleanupRetiredBrandIcons/,'Generic asset deletion reclaims logo icons');
assert.match(client,/retryBrandLogoCleanupCall/);
assert.match(client,/logoCleanupPending: boolean/);
assert.match(admin,/Retry old branding cleanup/);
assert.match(app,/result\.pendingCleanup/);
const gate=workflow.slice(workflow.indexOf('- name: Deploy safe Admin brand removal before Hosting'),workflow.indexOf('# Deploy paged Admin release queries'));
assert.ok(workflow.includes('[nightjar-safe-brand-removal]'));
assert.match(gate,/removeBrandLogo,retryBrandLogoCleanup,getBranding,submitImageAsset,moderateImageAsset,removeOwnedImageAsset/);
assert.match(gate,/gh run watch/);
console.log('PASS Admin branding atomic retirement, bounded cleanup receipts, stale approval protection and retry');
