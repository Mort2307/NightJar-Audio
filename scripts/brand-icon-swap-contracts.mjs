const gate=workflow.slice(workflow.indexOf('- name: Deploy atomic brand icon swaps before Hosting'),workflow.indexOf('# Deploy paged Admin release queries'));
assert.match(gate,/syncBrandIconVariants,retryBrandIconCleanup,getBranding/,'Exact backend selection');
assert.match(gate,/gh run watch/,'Hosting gated behind backend completion');
console.log('PASS staged icon upload, atomic swap, bounded safe cleanup, Admin retry and backend-first gate');
