import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const api=readFileSync('functions/src/index.ts','utf8');
const client=readFileSync('src/platform/firebase-media.ts','utf8');
const admin=readFileSync('src/components/AdminInstallBranding.tsx','utf8');
const workflow=readFileSync('.github/workflows/firebase-hosting-merge.yml','utf8');
const start=api.indexOf('export const syncBrandIconVariants = onCall');
const end=api.indexOf('export const getPendingImagePreview =',start);
assert.ok(start>0&&end>start,'Icon generation function exists');
const fn=api.slice(start,end);
const cleanupStart=api.indexOf('const cleanupRetiredBrandIcons = async');
const cleanup=api.slice(cleanupStart,start);
assert.ok(cleanupStart>0);
assert.match(fn,/const admin=requireAdminIdentity\(request\)/,'Only Admin can generate icon files');
assert.match(fn,/decodeExactBrandPng/,'All three images must be validated');
assert.match(fn,/const revision=String\(version\)\+'-'\+randomUUID\(\)/,'Unique staging paths prevent replacement races');
assert.match(fn,/Promise\.allSettled\(\[/,'Wait for every staged upload before proceeding');
assert.ok(fn.indexOf('await db.runTransaction(async tx=>')>fn.indexOf('const uploads=await Promise.allSettled'),'All bytes must stage before committing pointers');
assert.match(fn,/data\.logoAssetId!==branding\.logoAssetId/,'Stale generation rejects changed logo');
assert.match(fn,/iconVersion'\]\.some/,'Stale generation rejects competing icon changes');
assert.match(fn,/brandIconRemovalPending:retired/,'Old paths are receipted in canonical Firestore transaction');
assert.ok(fn.indexOf('const pendingCleanup=await cleanupRetiredBrandIcons()')>fn.indexOf('brandIconRemovalPending:retired'),'Cleanup follows pointer commit');
assert.doesNotMatch(fn,/await clearBrandingIconFiles\(branding\)/,'Never delete active icons before replacement commit');
assert.match(cleanup,/safeBrandIconPath\(path\)/,'Retired icon cleanup validates exact private path');
