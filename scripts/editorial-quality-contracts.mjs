/**
 * NightJar editorial hygiene checks.
 * Scan authored source text, not creator submissions or stored content.
 * Deliberately allow legal AI disclosures, punctuation, Markdown and credits.
 */
import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { relative, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const scopes = ['src/App.tsx', 'src/components', 'functions/src/publication-notifications.ts'];

const traps = [
  ['AI assistant disclosure accidentally used as UI prose', /\bas an (?:AI|artificial intelligence)(?: language)? model\b/i],
  ['AI-generated marketing byline', /\b(?:generated|written|created) by (?:ChatGPT|OpenAI|an AI)\b/i],
  ['generic AI attribution', /\b(?:powered by ChatGPT|ChatGPT wrote (?:this|the following))\b/i],
  ['unfinished lorem ipsum filler', /\blorem ipsum\b/i],
  ['unfinished copy placeholder', /\b(?:insert (?:your |the )?(?:name|title|description|copy|text|content) here|replace this (?:copy|text)|placeholder (?:copy|text) goes here)\b/i],
  ['unfilled editorial template marker', /\[\s*(?:insert (?:name|title|description|text)|todo:?\s*(?:write|add)|your name here)\s*\]/i],
  ['generic promotional filler', /\b(?:in today's fast[- ]paced world|delve into a world of|unlock your (?:creative )?potential|unleash your imagination|take your (?:creative )?journey to the next level)\b/i],
];
const identify = (value) => traps.filter(([, exp]) => exp.test(value)).map(([reason]) => reason);

for (const sample of [
  'As an AI language model I can help',
  'Generated by ChatGPT',
  'Lorem ipsum dolor sit amet',
  'Please insert your description here',
  '[INSERT TITLE]',
  "In today's fast-paced world",
  'Unlock your creative potential',
]) assert.ok(identify(sample).length, 'Editorial detector missed fixture: ' + sample);

for (const legitimate of [
  'Original manuscripts are not licensed for AI training.',
  'The artist confirms the work is human-created and not AI-generated.',
  'Your transcript stays on this device until you save.',
  'Use the [00:20] timestamp to mark a spoken line.',
  'Your account—your choice.',
]) assert.deepEqual(identify(legitimate), [], 'Legitimate wording must be allowed: ' + legitimate);

const files = [];
for (const scope of scopes) {
  const absolute = resolve(root, scope);
  if (!statSync(absolute).isDirectory()) { files.push(absolute); continue; }
  const collect = (dir) => {
    for (const name of readdirSync(dir)) {
      const item = join(dir, name);
      if (statSync(item).isDirectory()) { collect(item); continue; }
      if (/\.tsx?$/.test(name) && !/\.test\.tsx?$/.test(name)) files.push(item);
    }
  };
  collect(absolute);
}

const issues = [];
let inspected = 0;
for (const file of files) {
  const contents = readFileSync(file, 'utf8');
  const source = ts.createSourceFile(file, contents, ts.ScriptTarget.Latest, true,
    file.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const inspect = (node) => {
    if (
      ts.isJsxText(node) ||
      ts.isStringLiteral(node) ||
      ts.isNoSubstitutionTemplateLiteral(node) ||
      ts.isTemplateHead(node) ||
      ts.isTemplateMiddle(node) ||
      ts.isTemplateTail(node)
    ) {
      inspected++;
      for (const reason of identify(node.text)) {
        const line = source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1;
        issues.push(relative(root, file) + ':' + line + ': ' + reason);
      }
    }
    ts.forEachChild(node, inspect);
  };
  inspect(source);
}
if (issues.length) {
  console.error('Editorial hygiene failed:\n' + issues.join('\n'));
  process.exitCode = 1;
} else {
  console.log('PASS NightJar editorial hygiene: ' + files.length + ' source files, ' + inspected + ' text nodes');
}
