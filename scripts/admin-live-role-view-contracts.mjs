import assert from 'node:assert/strict';
import fs from 'node:fs';

const app = fs.readFileSync('src/App.tsx', 'utf8');
const css = fs.readFileSync('src/index.css', 'utf8');
const market = fs.readFileSync('src/components/ScriptMarketplace.tsx', 'utf8');

assert.match(app, /type TestingMode = 'off' \| 'demo' \| 'simulation' \| 'live'/, 'session supports a separate live role view');
assert.match(app, /mode === 'live' \? 'live'|parsed\?\.mode === 'live' \? 'live'/, 'live mode persists across refresh');
assert.match(app, /const liveRolePreview = role === 'admin' && Boolean\(previewRole\) && !simulationMode && !demoMode/, 'only signed-in admins can enter non-demo read-only preview');
assert.match(app, /const selectPreviewRole = \(next: PreviewRole\) => \{[\s\S]*?setDemoMode\(false\)/, 'role switching explicitly turns off fictional data');
assert.match(app, /className="nj-live-switcher" ref=\{liveRoleMenuRef\}/, 'Owner role tools must be in their own compact dropdown, not the main navigation');
assert.match(app, /aria-expanded=\{liveRoleMenuOpen\}/, 'the role dropdown must expose accessible expanded state');
assert.match(app, /aria-controls="nj-live-switcher-menu"/, 'the role dropdown exposes its controlled menu');
assert.match(app, /const onOutside = \(event: PointerEvent\)/, 'the role menu closes when users click away');
assert.match(app, /const onEscape = \(event: KeyboardEvent\)/, 'the role menu closes with Escape');
assert.doesNotMatch(app, /className="admin-preview-strip"/, 'the overflowing unstyled role strip must not return');
const nav = app.split('<nav className={menuOpen ?')[1]?.split('</nav>')[0] ?? '';
assert.match(nav, />Discover<\/button>/, 'primary app navigation retains Discover');
assert.match(nav, /Creators & Work.*Directory/, 'primary navigation preserves both listener discovery and professional Directory');
assert.match(nav, />Library<\/button>/, 'primary app navigation retains Library');
assert.match(nav, />Admin<\/button>/, 'primary app navigation retains Admin for Owners');
assert.doesNotMatch(nav, /nj-live-switcher/, 'role controls must stay separate from normal app navigation');
assert.match(css, /\.nj-live-switcher-popover/, 'role menu must have an actual popup layout');
assert.match(css, /\.nj-live-switcher-options/, 'role actions have explicit spacing and touch targets');
assert.match(css, /max-width: 1120px/, 'navigation collapses before crowded medium desktop widths');
assert.match(css, /max-width: 520px/, 'phone header keeps role button compact');
assert.match(app, /View live Listener/, 'the owner can choose the actual Listener UI');
assert.match(app, /View live VA Creator/, 'the owner can choose the actual Creator UI');
assert.match(app, /const creatorOnly = effectiveRole === 'creator' && !liveRolePreview/, 'admin preview does not become an authorised Creator account');
assert.match(app, /!liveRolePreview && \['creator','writer','editor','artist'\]/, 'preview does not load private messaging UI');
assert.match(app, /if \(!user \|\| !ageVerified \|\| !professional \|\| !professionalActive \|\| liveRolePreview\)/, 'preview avoids private conversations endpoint');
assert.match(app, /nightjar-read-only-preview/, 'view interaction boundary is mounted');
assert.match(app, /onClickCapture=\{\(event\) => \{[\s\S]*?if \(!liveRolePreview\) return;/, 'clicks that could mutate data are blocked');
assert.match(app, /data-nj-preview-safe="true"/, 'public browsing remains usable within read-only mode');
assert.match(app, /onKeyDownCapture=\{\(event\) => \{[\s\S]*?if \(!liveRolePreview \|\| event\.key === 'Tab'\) return;/, 'keyboard mutation paths are blocked');
assert.match(app, /onSubmitCapture=\{\(event\) => \{ if \(liveRolePreview/, 'form submissions are blocked');
assert.match(app, /readOnlyPreview=\{canAdmin && !demoMode\}/, 'Script Marketplace uses read-only public listings');
assert.match(market, /if \(readOnlyPreview\)/, 'interest cannot be submitted from admin perspective');
assert.match(market, /data-nj-preview-safe=\{readOnlyPreview \? "true"/, 'public Writer profiles remain navigable from the marketplace');
assert.match(app, /<AdminLiveMarketplacePreview/, 'actual script-visibility audit remains available');
assert.match(css, /\.nightjar-live-role-banner/, 'obvious live status marker is styled');

