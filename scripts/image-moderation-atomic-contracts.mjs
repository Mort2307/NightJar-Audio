import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync('functions/src/index.ts','utf8');
const hosting=readFileSync('.github/workflows/firebase-hosting-merge.yml','utf8');
const a=src.indexOf('export const moderateImageAsset = onCall');
const b=src.indexOf('\nexport const ',a+40);
assert.ok(a>=0&&b>a,'Image Admin moderation callable exists');
const fn=src.slice(a,b);
assert.match(fn,/requireAdminIdentity\(request\)/,'Only Admin can decide image moderation');
assert.match(fn,/db\.runTransaction\(async transaction=>/,'Moderation and link transition atomic');
assert.match(fn,/const imageSnapshot=await transaction\.get\(ref\)/);
assert.match(fn,/asset\.status!=='pending'/,'Reviewed, removed or superseded images cannot be accepted');
assert.match(fn,/const targetSnapshot=await transaction\.get\(targetRef\)/);
assert.match(fn,/parent\[pendingField\]===assetId/,'Reviewer must check active pending image');
assert.match(fn,/decision==='approved' && !current/,'Stale approval rejected');
assert.match(fn,/oldSnapshot=oldRef\?await transaction\.get\(oldRef\)/);
assert.match(fn,/transaction\.set\(ref,moderation,\{merge:true\}\)/);
assert.match(fn,/if\(current\)transaction\.set\(targetRef,parentUpdate,\{merge:true\}\)/,'Commit asset and parent together');
assert.match(fn,/status:previousPath\?'removing':'removed',publicUrl:null,storageRemovalPendingPath/,'Retire prior approved image before file deletion; metadata-only images finish directly');
assert.ok(fn.indexOf('await getStorage().bucket().file(entry.path).delete')>fn.indexOf('return {asset:{kind,ownerUserId:owner,targetId:target},cleanup}'),'Private Storage deletion must be after moderation commit');
assert.match(fn,/status:decision==='approved'\?'approved':'rejected'/);
assert.match(fn,/moderationPolicy:'no-explicit-imagery-v1'/);
assert.match(fn,/approvedWorkThankYou\(String\(asset.ownerUserId\),'artwork',null\)/,'Keep personalised Artist approval thank-you');
assert.match(fn,/dedupeKey:'image-moderation:'/,'Notification retry must be stable');
assert.match(fn,/pendingCleanup/,'Do not lose failed file cleanup');
assert.doesNotMatch(fn,/await clearAssetFile\(/,'Do not silently swallow Storage deletion in moderation');
const remove=src.slice(src.indexOf('export const removeOwnedImageAsset = onCall'),src.indexOf('export const removeProfileAvatar = onCall'));
assert.match(remove,/status:'removing',publicUrl:null,storageRemovalPendingPath/,'Member removal uses same retired state');
const gate=hosting.slice(hosting.indexOf('- name: Deploy atomic image decisions before Hosting'),hosting.indexOf('# Deploy paged Admin release queries'));
assert.match(gate,/moderateImageAsset/);
assert.match(gate,/gh run watch/,'Image decision backend must deploy before Hosting');
assert.ok(hosting.includes('[nightjar-image-decision-atomic-release]'));
console.log('PASS image moderation atomic approval/rejection, prior retirement, linked status and production gate');
