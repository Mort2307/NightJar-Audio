import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const fn=readFileSync(new URL('../functions/src/index.ts',import.meta.url),'utf8');
const fragment=fn.slice(fn.indexOf('const retiredReleaseAudioPaths='),fn.indexOf('export const submitReleaseForModeration = onCall'));
const final=fragment.slice(fragment.indexOf('export const finalizeReleaseAudio'),fragment.indexOf('export const removeReleaseAudio'));
const removal=fragment.slice(fragment.indexOf('export const removeReleaseAudio'));
assert.match(final,/requireAccountRole\(request, \['creator'\]\)/);
assert.match(final,/storagePath\.startsWith\(expectedPrefix\)/);
assert.match(final,/file\.getMetadata\(\)/);
assert.match(final,/db\.runTransaction\(async tx =>/);
assert.match(final,/const snap = await tx\.get\(ref\)/);
assert.match(final,/current\.creatorUserId !== identity\.uid/);
assert.match(final,/if\(attached\) return \{alreadyAttached:true/);
assert.match(final,/retiredReleaseAudioPaths\(current,''\)\.includes\(storagePath\)/);
assert.match(final,/retiredAudioPaths:retiredReleaseAudioPaths\(current,oldPath/);
assert.match(final,/oldPath\)\{[\s\S]*delete\(\{ignoreNotFound:true\}\)/);
assert.ok(!final.includes('await ref.set('), 'No precondition-free writes after initial fetch');
assert.ok(!final.includes('file.delete('),'Cannot delete potential attached file during non-transactional validation');
assert.match(removal,/db\.runTransaction\(async tx=>/);
assert.match(removal,/retiredAudioPaths:retiredReleaseAudioPaths\(current,oldPath\)/);
assert.ok(removal.indexOf('tx.set(ref,')<removal.indexOf("file(path).delete"), 'Detach before deleting bytes');
assert.match(fragment,/slice\(-32\)/);
console.log('Atomic audio finalization and retired-path guards verified.');
