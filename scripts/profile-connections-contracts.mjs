import { strict as assert } from 'node:assert';
import { readFileSync } from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const server=read('functions/src/index.ts');
const indexes=JSON.parse(read('firestore.indexes.json'));
const client=read('src/platform/firebase-community.ts');
const connections=read('src/components/ProfileConnections.tsx');
const page=read('src/components/ProfileConnectionsPage.tsx');
const pageCss=read('src/styles/nightjar-connections-page.css');
const profile=read('src/components/PublicProfile.tsx');
const legacy=read('src/components/CreatorProfile.tsx');
const app=read('src/App.tsx');
const directory=read('src/components/ProfessionalLibrary.tsx');
const spotlight=read('src/components/SpotlightExperience.tsx');
const css=read('src/styles/nightjar-velvet-interaction.css');
const main=read('src/main.tsx');

assert.match(server,/export const listPublicProfileConnections = onCall/);
assert.match(server,/await requireAgeVerified\(identity\.uid\)/);
const secure=server.slice(server.indexOf('export const listPublicProfileConnections = onCall'),server.indexOf('export const setProfileFollow = onCall'));
assert.match(secure,/\.limit\(limit\)/,'both kinds of queries are bounded');
assert.match(secure,/member\.status !== 'active'/,'suspended accounts excluded');
assert.match(secure,/publicData\.publicProfile === false/,'private profiles excluded');
assert.match(secure,/adminCommunityVisible !== true/,'private admin accounts excluded');
assert.doesNotMatch(secure,/email:|phone:|dateOfBirth:|didit/,'connections never return sensitive identity or verification');
assert.match(secure,/\.collectionGroup\('follows'\)\.where\('targetUserId'/,'follower reverse lookup uses indexed query');
assert.ok(indexes.fieldOverrides.some(x=>x.collectionGroup==='follows'&&x.fieldPath==='targetUserId'&&x.indexes?.some(i=>i.queryScope==='COLLECTION_GROUP')),'follower lookup has Firestore collection group index');
assert.match(client,/listPublicProfileConnectionsCall/);
assert.doesNotMatch(profile,/setConnectionKind/,'Social list must not expand inside public profile');
assert.match(profile,/onOpenConnections/);
assert.match(profile,/className="nj-profile-metric-button"/);
assert.match(profile,/goToSection\(target!\)/);
assert.match(legacy,/onOpenConnections/,'Legacy creator profiles navigate to social page');
assert.doesNotMatch(legacy,/setConnectionKind/,'Legacy profile no longer expands a connection card');
assert.match(app,/connectionsPage/,'App controls a dedicated social navigation destination');
assert.match(app,/onOpenConnections=\{/,'Both public profile paths navigate to the dedicated page');
assert.match(app,/<ProfileConnectionsPage/);
assert.match(connections,/publicly visible members/);
assert.match(connections,/onOpenProfile\(person\.userId,person\.role\)/);
assert.match(connections,/aria-busy=\{loading\}/);
assert.match(directory,/nj-directory-identity-trigger/);
assert.match(spotlight,/nj-spotlight-portrait-trigger/);
assert.match(app,/nj-release-cover-trigger/);
assert.match(app,/kind:'followers'/,'profile owner can open full-page followers');
assert.match(app,/kind:'following'/,'profile owner can open full-page following');
assert.match(server,/userId !== identity\.uid/,'owners can see own follows without exposing private accounts');

assert.match(page,/role="dialog" aria-modal="true"/,'Connections is its own full-screen accessible page');
assert.match(page,/role="tablist"/,'Followers and Following both have interactive tabs');
assert.match(page,/onClick=\{onBack\}/,'Explicit Back to profile navigation exists');
assert.match(page,/useDialogFocusTrap/,'Full-screen page traps and restores focus');
assert.match(connections,/embedded/,'Connection list can render without an embedded popup header');
assert.match(pageCss,/height:100dvh/,'Full-screen page fills mobile viewport');
assert.match(pageCss,/data-nightjar-vision/,'Alternative Vision Access palettes are retained');
assert.match(pageCss,/prefers-reduced-motion/,'Page transitions honour reduced motion');
assert.match(main,/nightjar-connections-page\.css/,'New social page CSS is loaded');
assert.ok(main.indexOf('nightjar-connections-page.css') < main.indexOf('vision-access.css'),'Vision Access rules remain last');
assert.match(css,/prefers-reduced-motion/);
assert.match(css,/data-nightjar-vision/);
assert.match(main,/nightjar-velvet-interaction\.css/);
assert.ok(main.indexOf('nightjar-velvet-interaction.css')<main.indexOf('vision-access.css'));
console.log('PASS bounded, privacy-filtered public connections and NightJar tappable surface contracts');
