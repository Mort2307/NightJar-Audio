import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync('functions/src/index.ts','utf8');
const u=readFileSync('src/components/WriterScriptArtwork.tsx','utf8');
const c=readFileSync('src/platform/firebase-media.ts','utf8');
const hosting=readFileSync('.github/workflows/firebase-hosting-merge.yml','utf8');
const start=src.indexOf('export const removeOwnedImageAsset = onCall');
const end=src.indexOf('\nexport const ',start+50);
assert.ok(start>=0&&end>start);
const fn=src.slice(start,end);
assert.match(fn,/requireActiveIdentity\(request\)/);
assert.match(fn,/db\.runTransaction\(async transaction=>/);
assert.match(fn,/const snap=await transaction\.get\(ref\)/);
assert.match(fn,/const targetSnapshot=targetRef \? await transaction\.get\(targetRef\)/);
assert.match(fn,/owner!==identity\.uid && !scriptAuthor/);
assert.match(fn,/kind==='brand_logo' && !identity\.admin/);
assert.match(fn,/storagePath===allowedPrefix\+ext/,'Only canonical owner+asset images may be deleted');
assert.match(fn,/transaction\.set\(targetRef,next,\{merge:true\}\)/,'Parent unlink is transactional');
assert.match(fn,/status:'removing',publicUrl:null,storageRemovalPendingPath/,'Image public access is revoked before deletion');
assert.ok(fn.indexOf('await getStorage().bucket().file(retirement.path).delete')>fn.indexOf('return {done:false,path:storagePath}'),'Storage deletion must follow committed retirement');
assert.match(fn,/pendingCleanup:true/,'Ambiguous deletion must remain retryable');
assert.match(fn,/status:'removed',publicUrl:null,storageRemovalPendingPath:null/,'Final removal only after Storage success');
assert.match(fn,/scriptAuthor=kind==='script_artwork'/,'Keep real manuscript author rights');
for(const kind of ['profile_avatar','profile_banner','brand_logo','social_avatar','artist_portfolio','release_artwork','script_artwork'])
  assert.ok(fn.includes("kind==='"+kind+"'"),'Missing image parent '+kind);
assert.match(src,/if \(!asset \|\| asset\.status !== 'approved'\)/,'Image delivery must deny retired assets');
assert.match(u,/Retry private artwork cleanup/);
assert.match(u,/result\.pendingCleanup/);
assert.match(u,/window\.localStorage\.setItem\(cleanupKey,id\)/,'Retry hint survives reload without storing content');
assert.match(c,/pendingCleanup: boolean/);
const marker='[nightjar-safe-image-removal-release]';
assert.ok(hosting.includes(marker),'Release must have backend-first gate');
const gate=hosting.slice(hosting.indexOf('- name: Deploy transaction-first image removal before Hosting'),hosting.indexOf('# Deploy paged Admin release queries'));
assert.match(gate,/removeOwnedImageAsset/);
assert.match(gate,/gh run watch/);
console.log('PASS image asset+parent transactional retirement, ownership, retry, private delivery and backend-first deployment');
