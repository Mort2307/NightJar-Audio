import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const calendar=readFileSync('src/components/PersonalCalendar.tsx','utf8');
const fn=calendar.slice(calendar.indexOf('  const refresh = () => {'),calendar.indexOf('\n\n  const today =',calendar.indexOf('  const refresh = () => {')));
assert.match(fn,/fetchEpoch\.current/,'role switches invalidate in-flight responses');
assert.match(fn,/const active=\(\)=>fetchEpoch\.current===epoch/);
assert.match(fn,/void nightjarCalendar\.get\(\)/,'private dates start immediately');
assert.match(fn,/void nightjarCalendar\.upcoming\(\)/,'upcoming requests independently');
assert.match(fn,/void nightjarCatalogue\.list\(\)/,'approved published releases remain visible');
assert.match(fn,/nightjarCatalogue\.adminAudioLibrary\(\)/,'admin calendar retains moderation schedule');
assert.match(fn,/nightjarCatalogue\.dashboard\(\)/,'creator calendar retains scheduling');
assert.doesNotMatch(fn,/await /,'no sequential blocking requests on calendar open');
assert.match(fn,/setLoading\(false\)/,'private calendar becomes interactive when just its own request settles');
assert.match(fn,/setUpcomingLoading\(false\)/);
assert.match(fn,/setPublishedLoading\(false\)/);
assert.match(fn,/setScheduleLoading\(false\)/);
assert.match(calendar,/return \(\)=>\{fetchEpoch\.current\+\+;\}/,'unmount invalidates stale results');
assert.match(calendar,/upcomingLoading\?<p/);
assert.match(calendar,/publishedLoading\?<p/);
assert.match(calendar,/Loading your private calendar dates/);
assert.match(calendar,/communityFilter==='following'/);
assert.match(calendar,/nightjarCalendar\.save\(\{id:editing \?\? undefined,title:title\.trim\(\),date:draftDate/);
console.log('Calendar fast-load regression contracts PASS: independent feeds, private editing and account/role isolation');
