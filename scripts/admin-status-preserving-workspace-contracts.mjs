import assert from 'node:assert/strict';
import fs from 'node:fs';

const backend = fs.readFileSync('functions/src/index.ts','utf8');
const client = fs.readFileSync('src/platform/firebase-administration.ts','utf8');
const app = fs.readFileSync('src/App.tsx','utf8');
const begin = backend.indexOf('export const adminSetAccountWorkspace = onCall');
const end = backend.indexOf('export const listBillingSubscriptions = onCall', begin);
assert.ok(begin > 0 && end > begin, 'Owner workspace-only API must exist');
const section = backend.slice(begin,end);
assert.match(section,/requireAdminIdentity\(request\)/,'workspace control is owner-only');
assert.match(section,/db\.runTransaction/,'the current status and roles are read atomically');
assert.match(section,/ADMIN_EMAILS\.has/,'owner accounts cannot be reassigned');
assert.match(section,/account\.status === 'suspended'/,'suspended members cannot switch workspaces');
assert.match(section,/approved\.includes\(role as AccountRole\)/,'only approved professional workspaces are permitted');
assert.match(section,/const status = cleanText\(account\.status, 30\) \|\| 'active'/,'caller receives persisted status');
assert.match(section,/tx\.set\(ref, \{/,'workspace change persists');
const write = section.slice(section.indexOf('tx.set(ref, {'),section.indexOf('}, { merge: true });')+20);
assert.doesNotMatch(write,/\bstatus\s*:/,'workspace selection must never activate a suspended or pending account');
assert.doesNotMatch(write,/approvedProfessionalRoles\s*:/,'workspace selection must not grant new roles');
assert.match(client,/'adminSetAccountWorkspace'/,'client calls protected workspace selector');
assert.match(client,/async setAccountWorkspace\(/,'workspace selector has a dedicated client method');
const roleStart = app.indexOf('const changeAccountRole = async');
const statusStart = app.indexOf('const changeAccountStatus = async',roleStart);
assert.ok(roleStart>0 && statusStart>roleStart,'Owner role and status handlers remain independent');
const roleUi = app.slice(roleStart,statusStart);
assert.match(roleUi,/setAccountWorkspace\(account\.userId, nextRole\)/,'live role selection uses status-preserving callable');
assert.doesNotMatch(roleUi,/status\s*:\s*'active'/,'demo role selection must not reactivate members');
assert.doesNotMatch(roleUi,/setAccountRole\(/,'role selection does not use status setter');
assert.match(app.slice(statusStart),/setAccountRole\(account\.userId, account\.role, nextStatus\)/,'explicit status control remains intact');
console.log('Nightjar Owner workspace changes preserve account suspension/review status.');
