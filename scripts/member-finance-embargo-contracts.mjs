import assert from 'node:assert/strict';
import fs from 'node:fs';

const read = (path) => fs.readFileSync(path,'utf8');
const app=read('src/App.tsx');
const home=read('src/components/NightjarHomeLayout.tsx');
const visibility=read('src/platform/nightjar-financial-visibility.ts');
const settings=read('src/components/NightjarSettings.tsx');
const profile=read('src/components/PublicProfile.tsx');
const script=read('src/components/ScriptMarketplace.tsx');
const actions=read('src/components/MarketplaceScriptActions.tsx');
const rights=read('src/components/WriterRightsPanel.tsx');
const notifications=read('src/components/NotificationPreferences.tsx');
const glossary=read('src/components/HelpGlossary.tsx');
const backend=read('functions/src/index.ts');

assert.match(visibility,/MEMBER_PAYMENT_FEATURES_ENABLED = false/, 'beta payment controls remain embargoed');
assert.doesNotMatch(app,/<TransparencyPanel|nj-home-transparency|<HomeSection id="studio"|studio-feature-copy/, 'home has no planning/pay promotional sections');
assert.doesNotMatch(home,/Creator opportunities|\| 'studio'/, 'home arrangement editor cannot resurrect removed cards');
assert.match(app, /MEMBER_PAYMENT_FEATURES_ENABLED && effectiveRole !== 'admin' && <Suspense[^\n]*Nightjar wallet/, 'member wallet is gated');
assert.match(app, /onSupport=\{MEMBER_PAYMENT_FEATURES_ENABLED \?/, 'professional library gift actions are gated');
assert.match(app, /MEMBER_PAYMENT_FEATURES_ENABLED && supportTarget && !liveRolePreview/, 'gift modal is gated');
assert.match(profile, /MEMBER_PAYMENT_FEATURES_ENABLED && !readOnlyPreview/, 'public professional gifts are gated');
assert.match(profile, /MEMBER_PAYMENT_FEATURES_ENABLED && giftOpen/, 'public gift dialog is gated');
assert.match(app, /MEMBER_PAYMENT_FEATURES_ENABLED && creatorOnly && accountStatus !== 'pending_review'/, 'creator paid negotiation area is gated');
assert.match(app, /MEMBER_PAYMENT_FEATURES_ENABLED && <WorkspaceSection[^\n]*writer-negotiations/, 'writer paid negotiation area is gated');
assert.doesNotMatch(settings,/Subscription and billing|nj-settings-billing/, 'account settings has no payment-planning placeholder');
assert.doesNotMatch(script,/Indicative fee|commissionPricePence/, 'marketplace has no public fee');
assert.doesNotMatch(rights,/Indicative commission price \(£\)/, 'writer studio has no price setting');
assert.match(actions,/MEMBER_PAYMENT_FEATURES_ENABLED&&<button[^\n]*Make rights offer/, 'payment offer button is gated');
assert.match(actions,/next==='licence'&&!MEMBER_PAYMENT_FEATURES_ENABLED/, 'paid offer mode cannot be opened by a member');
assert.doesNotMatch(notifications, /\['payments','Payment updates'\]/, 'payment notices are not advertised before launch');
assert.match(glossary,/!\['licence-price','counteroffer'\]\.includes\(id\)/, 'fee and counteroffer terms are hidden in member glossary');
assert.doesNotMatch(app,/notifyWithAction\(message, 'Subscribe'/, 'paywall does not advertise checkout');
const snapshot=backend.slice(backend.indexOf('export const transparencySnapshot'),backend.indexOf('const CREATIVE_MESSAGE_ROLES',backend.indexOf('export const transparencySnapshot')));
assert.match(snapshot,/requireAccountRole\(request, \['admin'\]\)/,'commercial snapshot requires administrator');
const access=backend.slice(backend.indexOf('export const myListeningAccess'),backend.indexOf('const professionalRolesForAccount',backend.indexOf('export const myListeningAccess')));
assert.match(access,/identity\.admin \? readCommercialSettings\(\) : Promise\.resolve\(null\)/,'member entitlement access does not read private commercial settings');
assert.match(access,/planningMonthlyPricePence: identity\.admin \?/, 'price redacted for non-admin');
assert.match(access,/subscriptionUrl: identity\.admin \?/, 'checkout URL redacted for non-admin');
const market=backend.slice(backend.indexOf('export const listScriptMarketplace'),backend.indexOf('export const getMarketplaceScriptSample'));
assert.match(market,/commissionPricePence: _hiddenIndicativePrice/,'backend omits indicative script fee from member discovery');
const giftApi=read('functions/src/nightjars.ts');
for(const fn of ['nightjarGiftConfig','myNightjarWallet','sendNightjars','myNightjarEarnings','myNightjarGiftHistory']) {
  const start=giftApi.indexOf('export const '+fn+' = onCall');
  assert.ok(start>=0,fn+' should remain available for administrator testing');
  const next=giftApi.indexOf('export const ',start+15);
  const body=giftApi.slice(start,next>=0?next:undefined);
  assert.match(body,/await requireAdmin\(request\)/,fn+' must not be callable by members during payment embargo');
}
console.log('Nightjar beta payment visibility and backend price-redaction contracts PASS.');
