import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const fn=readFileSync(new URL('../functions/src/index.ts',import.meta.url),'utf8');
const start=fn.indexOf('const createNotification = async');
const end=fn.indexOf('// Moderation feedback',start);
const block=fn.slice(start,end);
assert.match(block,/const oncePerKey=dedupeKey && payload\.oncePerKey===true/);
assert.match(block,/db\.runTransaction\(async tx=>/);
assert.match(block,/const existing=await tx\.get\(ref\)/);
assert.match(block,/if\(existing\.exists\)return false/);
assert.match(block,/tx\.create\(ref,/);
assert.match(block,/if\(!created\)return/);
assert.ok(block.indexOf('if(!created)return')<block.indexOf('await deliverPushNotification'),'No second push after stable event');
assert.match(block,/delete persistedPayload\.oncePerKey/);
assert.match(block,/else\{[\s\S]*await ref\.set\(/);
assert.match(fn,/dedupeKey:'scheduled-live-'\+doc\.id,oncePerKey:true/);
assert.match(fn,/dedupeKey:'writer-script-review:'\+scriptId\+':'\+reviewEventRef\.id,oncePerKey:true/);
assert.doesNotMatch(fn,/dedupeKey:'release-reaction:'[^\n]*oncePerKey:true/, 'Repeatable reactions remain coalescible');
console.log('Opt-in immutable event deduplication prevents repeat push; ordinary notifications preserved.');
