import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=readFileSync(new URL('../functions/src/index.ts',import.meta.url),'utf8');
const begin=src.indexOf('export const moderateEditorPortfolioItem = onCall');
const end=src.indexOf('export const getEditorPortfolioAudioUrl = onCall',begin);
const block=src.slice(begin,end);
assert.ok(begin>=0&&end>begin);
assert.match(block,/requireAdminIdentity\(request\)/);
assert.match(block,/db\.runTransaction\(async transaction=>/);
assert.match(block,/transaction\.get\(ref\)/);
assert.match(block,/data\.status!=='pending_review'/);
assert.match(block,/transaction\.set\(ref,/);
assert.match(block,/moderationNote:note\|\|null/);
assert.match(block,/dedupeKey:'editor-portfolio-review:'/);
assert.match(block,/\.catch\(error=>console\.warn\('Editor showcase review notification failed'/);
assert.doesNotMatch(block,/await ref\.set\(/,'A stale separate write must not replace another Admin decision');
const submitBegin=src.indexOf('export const submitEditorPortfolioItem = onCall');
const submitEnd=src.indexOf('export const editorPortfolioModerationQueue = onCall',submitBegin);
const submission=src.slice(submitBegin,submitEnd);
assert.ok(submitBegin>=0&&submitEnd>submitBegin,'Editor submit callable exists');
assert.match(submission,/db\.runTransaction\(async transaction =>/,'Submission is atomic');
assert.match(submission,/const snapshot = await transaction\.get\(ref\)/,'Read current rights and attachment inside the transaction');
assert.match(submission,/live\.ownerUserId !== identity\.uid/,'Submission must be owner-only');
assert.match(submission,/live\.status === 'pending_review'/,'Lost response can retry idempotently');
assert.match(submission,/\['draft', 'changes', 'rejected'\]/,'Only editable items can transition to review');
assert.match(submission,/Number\(live\.afterAudioByteSize \?\? 0\) <= 0/,'Do not submit unverified sample bytes');
assert.match(submission,/live\.rightsConfirmed !== true \|\| live\.contributorPermissionsConfirmed !== true/);
assert.match(submission,/transaction\.set\(ref, \{/,'Commit the review transition atomically');
assert.doesNotMatch(submission,/await ref\.set\(/,'Never separate validation and submission');
const workflow=readFileSync(new URL('../.github/workflows/firebase-hosting-merge.yml',import.meta.url),'utf8');
const editorGate=workflow.slice(workflow.indexOf('- name: Deploy atomic Editor moderation before Hosting'),workflow.indexOf('- name: ',workflow.indexOf('- name: Deploy atomic Editor moderation before Hosting')+20));
assert.match(editorGate,/submitEditorPortfolioItem,moderateEditorPortfolioItem/,'Deploy submission backend before Hosting');
assert.match(editorGate,/gh run watch/,'Do not ship UI before backend');
const i=src.indexOf('export const adminReviewWriterScript = onCall');
assert.match(src.slice(i,i+3400),/transaction\.create\(reviewEventRef/,'Writer reason remains durable/atomic');
console.log('Concurrent Editor review decision, reason and notification contracts passed.');
