import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = (file) => readFileSync(file,'utf8');
const player = read('src/components/NightjarPlayer.tsx');
const styles = read('src/components/nightjar-player-premium.css');
const eq = read('src/hooks/useNightjarEqualizer.ts');
assert.match(player, /nj-up-sheet/, 'single unified player is used');
assert.doesNotMatch(player, /nightjar-player-shell transcript-open|className="player-dock"/, 'legacy two-layer dock is removed');
assert.match(player, /className="nj-up-transcript-resizer"/, 'transcript has a resize grip');
assert.match(player, /onPointerMove/, 'touch drag changes transcript height');
assert.match(player, /onKeyDown=\{\(event\)/, 'keyboard resize is available');
assert.match(player, /transcriptMode === 'always_open'/, 'saved accessibility setting respected');
assert.match(player, /transcriptFollowPlayback/, 'follow playback preserved');
assert.match(player, /nightjarCatalogue\.transcript\(releaseId\)/, 'protected transcript fetch remains gated');
assert.match(player, /nightjarListening\.record/, 'listening analytics preserved');
assert.match(player, /nightjarListening\.resume/, 'playback resume preserved');
assert.match(player, /sleepTimerTimeout/, 'sleep timer preserved');
assert.match(player, /track\.artworkUrl/, 'creator art used when available');
assert.match(player, /nightjar-home-512\.png/, 'approved Nightjar logo fallback');
assert.match(player, /useNightjarEqualizer/, 'real EQ hook is connected');
for (const term of ['createMediaElementSource','createBiquadFilter','lowshelf','peaking','highshelf','AudioContext','mode: \'cors\'']) assert.ok(eq.includes(term), term + ' must be in the audio engine');
assert.match(eq, /if \(!response\.ok\)/, 'cross-origin EQ is guarded');
assert.match(eq, /route\(false\)/, 'EQ can be bypassed');
assert.match(styles, /var\(--plum-soft/, 'colours derive from user-selected theme');
assert.match(styles, /max-height:94dvh/, 'small-screen player fits viewport');
assert.match(styles, /prefers-reduced-motion/, 'reduced motion preserved');
console.log('Nightjar unified premium player regression contracts PASS.');
